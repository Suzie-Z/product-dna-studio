"""Development-only: pin SIL-OFL rounded fonts and export matching glyph outlines.
Runtime/Render uses committed assets and needs no fontTools installation.
"""
import io,json,urllib.request
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.subset import Subsetter,Options
from fontTools.pens.svgPathPen import SVGPathPen
ROOT=Path(__file__).resolve().parents[1];ASSETS=ROOT/'preview/assets';out={}
for key,family,filename,weight in [('heading','fredoka','Fredoka%5Bwdth%2Cwght%5D.ttf',600),('body','nunito','Nunito%5Bwght%5D.ttf',650)]:
 base='https://raw.githubusercontent.com/google/fonts/main/ofl/'+family+'/'
 data=urllib.request.urlopen(base+filename,timeout=30).read()
 font=TTFont(io.BytesIO(data));axes={a.axisTag:(weight if a.axisTag=='wght'else a.defaultValue)for a in font['fvar'].axes};font=instantiateVariableFont(font,axes,inplace=True)
 opts=Options();opts.layout_features=[];sub=Subsetter(options=opts);sub.populate(unicodes=list(range(0x250))+list(range(0x2000,0x2070)));sub.subset(font)
 # Keep canvas/SVG measurement and standalone outline export identical.
 for table in ['GSUB','GPOS','kern']:
  if table in font:del font[table]
 target=ASSETS/('pm-'+key+'.ttf');font.save(target)
 (ASSETS/(family+'-OFL.txt')).write_bytes(urllib.request.urlopen(base+'OFL.txt',timeout=30).read())
 glyphs={};glyphSet=font.getGlyphSet()
 for code,name in font.getBestCmap().items():
  pen=SVGPathPen(glyphSet);glyphSet[name].draw(pen)
  glyphs[chr(code)]={'advance':font['hmtx'][name][0],'path':pen.getCommands()}
 out[key]={'family':'PMDNA'+key.title(),'url':'/assets/'+target.name,'units':font['head'].unitsPerEm,'xHeight':font['OS/2'].sxHeight,'glyphs':glyphs}
 print(key,len(glyphs),target.stat().st_size)
licenses='\n\n'.join((ASSETS/(family+'-OFL.txt')).read_text()for family in ['fredoka','nunito'])
(ROOT/'preview/pm-fonts.js').write_text('/* Bundled rounded fonts; generated by tools/build_pm_fonts.py.\n'+licenses.replace('*/','* /')+'\n*/\nwindow.PM_DNA_FONTS='+json.dumps(out,ensure_ascii=True,separators=(',',':'))+';\n')
